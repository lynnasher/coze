#!/bin/bash

# ============================================================
# 智能刷题助手 - 快速更新脚本
# 用于代码更新后快速重新部署
# ============================================================

set -e

APP_DIR="/var/www/quiz-app"

echo "======================================"
echo "  智能刷题助手 - 快速更新"
echo "======================================"

# 进入项目目录
cd $APP_DIR

# 如果有 git 仓库，拉取最新代码
if [ -d ".git" ]; then
    echo "拉取最新代码..."
    git pull origin main
fi

# 安装依赖
echo "安装依赖..."
pnpm install --frozen-lockfile

# 构建项目
echo "构建项目..."
pnpm build

# 重启应用
echo "重启应用..."
pm2 restart quiz-app

echo ""
echo "======================================"
echo "  更新完成！"
echo "======================================"
pm2 status | grep "quiz-app"
